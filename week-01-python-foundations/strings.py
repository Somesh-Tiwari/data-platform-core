# strings_math.py - Day 1: Somesh's First Python Code

first_code = "Somesh's World"

# Basic printing
print(first_code)

# String length
print(len(first_code))

# Indexing and slicing
print(first_code[10])
print(first_code[0:6])
print(first_code[0:6:2])

# String methods
print(first_code.lower())
print(first_code.upper())
print(first_code.replace("World", "Universe"))
print(first_code.split(" "))
print(first_code.count("o"))
print(first_code.find("World"))

# f-string
print(f'{first_code} is my first message in python language')